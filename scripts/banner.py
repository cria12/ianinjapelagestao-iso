#!/usr/bin/env python3
"""Banner ASCII sem barras invertidas (o agetty interpreta '\\' em /etc/issue)."""
import sys

F = {
    "I": ["###", " # ", " # ", " # ", "###"],
    "A": [" ### ", "#   #", "#####", "#   #", "#   #"],
    "N": ["#   #", "##  #", "# # #", "#  ##", "#   #"],
    "J": ["  ###", "    #", "    #", "#   #", " ### "],
    "P": ["#### ", "#   #", "#### ", "#    ", "#    "],
    "E": ["#####", "#    ", "#### ", "#    ", "#####"],
    "L": ["#    ", "#    ", "#    ", "#    ", "#####"],
    "G": [" ####", "#    ", "#  ##", "#   #", " ####"],
    "S": [" ####", "#    ", " ### ", "    #", "#### "],
    "T": ["#####", "  #  ", "  #  ", "  #  ", "  #  "],
    "O": [" ### ", "#   #", "#   #", "#   #", " ### "],
}
for word in sys.argv[1:]:
    for row in range(5):
        print("  " + " ".join(F[c][row] for c in word).rstrip())
    print()
